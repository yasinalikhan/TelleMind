import { Injectable, inject, signal } from '@angular/core';
import { HttpClient, HttpHeaders } from '@angular/common/http';
import { Observable, tap, catchError, of } from 'rxjs';

export interface SavedQuery {
  id?: number;
  title: string;
  queryText: string;
  queryType: 'SQL' | 'NATURAL_LANGUAGE';
  description?: string;
  category?: string;
  chartType?: string;
  tenantId?: string;
  createdAt?: string;
  updatedAt?: string;
}

@Injectable({
  providedIn: 'root'
})
export class QueryService {
  private http = inject(HttpClient);
  private apiUrl = 'http://localhost:8080/api/queries';

  savedQueries = signal<SavedQuery[]>([]);
  loading = signal<boolean>(false);

  private getHeaders(): HttpHeaders {
    const token = localStorage.getItem('token');
    const tenantId = localStorage.getItem('tenantId') || 'tenant_1';
    return new HttpHeaders({
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${token}`,
      'X-Tenant-ID': tenantId
    });
  }

  loadQueries(): void {
    this.loading.set(true);
    const tenantId = localStorage.getItem('tenantId') || 'tenant_1';
    const localKey = `telemind_saved_queries_${tenantId}`;

    this.http.get<SavedQuery[]>(this.apiUrl, { headers: this.getHeaders() })
      .pipe(
        catchError(err => {
          console.warn('Backend queries API unavailable, loading from local cache:', err);
          const cached = localStorage.getItem(localKey);
          if (cached) {
            try {
              return of(JSON.parse(cached) as SavedQuery[]);
            } catch (e) {
              return of(this.getDefaultPresetQueries());
            }
          }
          return of(this.getDefaultPresetQueries());
        })
      )
      .subscribe({
        next: (queries) => {
          this.savedQueries.set(queries);
          localStorage.setItem(localKey, JSON.stringify(queries));
          this.loading.set(false);
        },
        error: () => this.loading.set(false)
      });
  }

  saveQuery(query: Partial<SavedQuery>): Observable<SavedQuery> {
    const tenantId = localStorage.getItem('tenantId') || 'tenant_1';
    const localKey = `telemind_saved_queries_${tenantId}`;

    return this.http.post<SavedQuery>(this.apiUrl, query, { headers: this.getHeaders() })
      .pipe(
        catchError(err => {
          console.warn('Backend unavailable, saving locally:', err);
          const localItem: SavedQuery = {
            id: Date.now(),
            title: query.title || 'Untitled Query',
            queryText: query.queryText || '',
            queryType: query.queryType || 'SQL',
            description: query.description || '',
            category: query.category || 'General',
            chartType: query.chartType || 'bar',
            tenantId: tenantId,
            createdAt: new Date().toISOString(),
            updatedAt: new Date().toISOString()
          };
          return of(localItem);
        }),
        tap((saved) => {
          const updated = [saved, ...this.savedQueries().filter(q => q.id !== saved.id)];
          this.savedQueries.set(updated);
          localStorage.setItem(localKey, JSON.stringify(updated));
        })
      );
  }

  deleteQuery(id: number): Observable<any> {
    const tenantId = localStorage.getItem('tenantId') || 'tenant_1';
    const localKey = `telemind_saved_queries_${tenantId}`;

    return this.http.delete(`${this.apiUrl}/${id}`, { headers: this.getHeaders() })
      .pipe(
        catchError(err => {
          console.warn('Backend unavailable, deleting locally:', err);
          return of({ message: 'Deleted locally' });
        }),
        tap(() => {
          const updated = this.savedQueries().filter(q => q.id !== id);
          this.savedQueries.set(updated);
          localStorage.setItem(localKey, JSON.stringify(updated));
        })
      );
  }

  getDefaultPresetQueries(): SavedQuery[] {
    return [
      {
        id: 1,
        title: 'Daily Revenue Trajectory (30D)',
        queryText: 'SELECT date, SUM(amount) AS amount FROM revenue GROUP BY date ORDER BY date',
        queryType: 'SQL',
        description: 'Revenue trendline grouped daily across all service categories',
        category: 'Financial',
        chartType: 'line'
      },
      {
        id: 2,
        title: 'Regional Revenue Leaderboard',
        queryText: 'SELECT region, SUM(amount) AS amount FROM revenue GROUP BY region ORDER BY amount DESC',
        queryType: 'SQL',
        description: 'Comparison of overall revenue generated by each province',
        category: 'Financial',
        chartType: 'bar'
      },
      {
        id: 3,
        title: 'Tariff Plan Market Composition',
        queryText: 'SELECT plan, COUNT(*) AS count FROM subscriber GROUP BY plan ORDER BY count DESC',
        queryType: 'SQL',
        description: 'Distribution of active and postpaid/prepaid subscription plans',
        category: 'Marketing',
        chartType: 'pie'
      },
      {
        id: 4,
        title: 'Tower Traffic Intensity Heatmap',
        queryText: 'SELECT region, tower, SUM(data_mb) AS data_mb FROM usage GROUP BY region, tower ORDER BY data_mb DESC',
        queryType: 'SQL',
        description: 'Cell tower network load and congestion intensity breakdown',
        category: 'Network',
        chartType: 'heatmap'
      },
      {
        id: 5,
        title: 'Core Network SLA Health Benchmark',
        queryText: 'SELECT kpi_name, metric_value, target_value FROM telecom_kpis ORDER BY kpi_name',
        queryType: 'SQL',
        description: 'Bullet benchmark of actual network uptime versus target threshold',
        category: 'SLA',
        chartType: 'bullet'
      },
      {
        id: 6,
        title: 'Compare Data Usage By Region',
        queryText: 'Compare data usage by region',
        queryType: 'NATURAL_LANGUAGE',
        description: 'Natural language query for bandwidth breakdown by province',
        category: 'Network',
        chartType: 'bar'
      },
      {
        id: 7,
        title: 'High-Value VIP Subscribers',
        queryText: 'SELECT msisdn, region, recharge_amount FROM subscriber ORDER BY recharge_amount DESC LIMIT 10',
        queryType: 'SQL',
        description: 'Top spending customers leaderboard ranking',
        category: 'Customer',
        chartType: 'horizontal_bar'
      }
    ];
  }
}
